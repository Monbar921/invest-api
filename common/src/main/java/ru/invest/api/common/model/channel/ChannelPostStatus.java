package ru.invest.api.common.model.channel;

/**
 * Состояние поста в очереди канала.
 */
public enum ChannelPostStatus {
    /** ждёт публикации или повтора */
    PENDING,
    SENT,
    /** Telegram отклонил пост (бот не администратор канала, канал не найден, текст не принят) - не повторяется */
    FAILED,
    /** не опубликован до срока актуальности: лимит постов в день, ночь, нет связи */
    SKIPPED
}
