package ru.invest.api.common.model.parameters;

/**
 * Поля, по которым можно сортировать список облигаций.
 */
public enum BondSortField {
    /** Уровень риска (LOW/MODERATE < HIGH < прочие) */
    RISK_LEVEL,
    /** Годовая доходность купона в % */
    COUPON_INTEREST,
    /** Дата погашения */
    MATURITY_DATE,
    /** Тикер */
    TICKER,
    /** Название */
    NAME,
    /** Текущая цена в рублях (для облигаций в иностранной валюте - по курсу ЦБ) */
    PRICE,
    /** Текущая цена в процентах от номинала */
    PERCENTAGE_PRICE,
    /** Эффективная доходность к погашению в % (с учётом НКД и амортизации) */
    YIELD_TO_MATURITY,
    /** Эффективная доходность к оферте в % */
    YIELD_TO_OFFER,
    /** Дюрация Маколея, лет */
    DURATION,
    /** Кредитный рейтинг по общей шкале: ASC - от худшего к лучшему */
    CREDIT_RATING,
    /** Средний дневной оборот за 30 дней в рублях */
    AVG_DAILY_TURNOVER,
    /** Спред к ОФЗ, п.п. */
    SPREAD_TO_OFZ
}
