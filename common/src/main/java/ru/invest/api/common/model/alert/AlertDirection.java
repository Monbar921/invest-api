package ru.invest.api.common.model.alert;

/**
 * Направление порога правила по цене или доходности.
 */
public enum AlertDirection {
    /** значение не ниже порога / выросло на порог */
    UP,
    /** значение не выше порога / снизилось на порог */
    DOWN,
    /** изменение в любую сторону; только для изменений цены, не для уровней */
    ANY
}
