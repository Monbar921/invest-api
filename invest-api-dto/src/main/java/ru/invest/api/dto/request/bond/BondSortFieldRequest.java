package ru.invest.api.dto.request.bond;

/**
 * Поля, по которым можно сортировать список облигаций.
 */
public enum BondSortFieldRequest {
    /** Уровень риска (LOW/MODERATE < HIGH < прочие) */
    RISK_LEVEL,
    /** Годовая доходность купона в % */
    COUPON_INTEREST,
    /** Дата погашения */
    MATURITY_DATE,
    /** Тикер */
    TICKER,
    /** Название */
    NAME,
    /** Текущая цена в рублях (для облигаций в иностранной валюте - по курсу ЦБ); облигации без цены в конце */
    PRICE,
    /** Текущая цена в процентах от номинала - не зависит от валюты; облигации без цены в конце */
    PERCENTAGE_PRICE,
    /** Эффективная доходность к погашению в % (с учётом НКД и амортизации); облигации, где её посчитать нельзя, в конце */
    YIELD_TO_MATURITY,
    /** Эффективная доходность к оферте в %; облигации без оферты в конце */
    YIELD_TO_OFFER,
    /** Дюрация Маколея, лет; облигации без дюрации в конце */
    DURATION,
    /** Кредитный рейтинг по общей шкале: ASC - от худшего к лучшему; облигации без рейтинга в конце */
    CREDIT_RATING,
    /** Средний дневной оборот за 30 дней в рублях; облигации без свечей в конце */
    AVG_DAILY_TURNOVER,
    /** Спред к ОФЗ, п.п.; облигации без спреда в конце */
    SPREAD_TO_OFZ
}
