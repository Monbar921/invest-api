package ru.invest.api.alert.service.usecase;

import java.time.LocalDate;

/**
 * Дайджест портфеля: стоимость и её изменение, выплаты периода, новости по облигациям портфеля.
 */
public interface PortfolioDigestUseCase {
    /**
     * Поставить в очередь дайджесты, которым пора: ежедневные - каждый день, еженедельные - в день недели из настроек.
     * Пустой дайджест не отправляется; повторный вызов в тот же день ничего не дублирует.
     *
     * @return сколько дайджестов поставлено в очередь
     */
    int sendDue(LocalDate today);

    /**
     * Один дайджест, независимо от дня недели.
     *
     * @return true - поставлен в очередь, false - пустой, правило выключено или уже отправлен сегодня
     */
    boolean send(Long alertId, LocalDate today);
}
