package ru.invest.api.alert.service.usecase;

/**
 * Уведомления по сохранённым фильтрам: новые облигации в выборке после обновления цен.
 */
public interface FilterAlertCheckUseCase {
    /**
     * Проверить все включённые правила SAVED_FILTER.
     *
     * @return сколько уведомлений поставлено в очередь
     */
    int checkAll();

    /**
     * Проверить одно правило. Правило без отправной точки (только что включено, изменён фильтр) только запоминает
     * текущую выборку и ничего не шлёт.
     */
    int check(Long alertId);
}
